"""Issued jobs may wait only for materials, never for a preferred start date.

The rolling-horizon MILP and the physical executor enforce the same rule.
After shipments and all starts for a day, a positive waiting quantity must
have at least one finite direct component insufficient for ONE more unit.
Partial starts and allocation between competing jobs remain supported.
"""
from collections import Counter, defaultdict
from fractions import Fraction
import math

RULE = 'MATERIAL_READY_IMMEDIATE_START_V1'


def requirements(data, product):
    """Aggregate repeated BOM edges; unlimited external inputs do not constrain starts."""
    finite = set(data['P']) | set(data['raw'])
    amounts = Counter()
    for child, amount, _ in data['bom'].children[product]:
        if child in finite:
            if amount <= 0 or int(amount) != amount:
                raise ValueError('Immediate-start runtime requires integer stock-unit BOM coefficients')
            amounts[child] += int(amount)
    return dict(amounts)


def startable_quantity(data, inventory, job):
    limits = [int(job['q'])]
    for child, amount in requirements(data, job['p']).items():
        # Physical receipts, stock and direct BOM usage are integer quantities.
        stock = inventory[child]
        if not math.isfinite(stock) or stock < 0 or int(stock) != stock:
            raise ValueError(f'Noninteger/negative physical component stock: {child}={stock}')
        limits.append(int(stock) // amount)
    return min(limits)


def assert_immediate_starts(data, inventory, queue, day):
    """Fail before accepting a day if an issued job can still start any quantity."""
    for job in queue:
        if job['q'] and startable_quantity(data, inventory, job):
            raise AssertionError(
                f'{RULE}: day={day}, job={job["id"]}, product={job["p"]}, '
                f'issued_day={job["created"]}, waiting={job["q"]}; materials are available')


def extend(model, meta, data, spec):
    """Add hard non-idling constraints without changing legacy code or objective.

For each product p/day k: u[p,k,age] <= U[p,k,age] * sum_c shortage[p,c,k].
shortage=1 implies I[c,k] < BOM[p,c]. With no finite children, u=0.
I is post-allocation stock, so shared materials cannot be assigned twice.

Manufactured states are integer-implied. Future raw stock is on the lattice
generated by integer quantities and (1-reject_probability). A half-lattice
gap represents strict shortage without rounding expected accepted receipts.
Actual day-zero raw stock is integer. Reject probability stays unchanged.
"""
    if 'production_start_rule' in meta:
        raise ValueError('Immediate-start constraints already installed')
    raw_step = 1 / Fraction(str(spec['supply']['reject_probability'])).denominator
    waits = defaultdict(list)
    for (kind, product, k, age), j in meta['av'].items():
        if kind == 'u' and model.ub[j] > 0:
            waits[product, k].append(j)
    shortages = {}
    for (product, k), waiting_vars in sorted(waits.items()):
        components = requirements(data, product)
        if not components:
            for j in waiting_vars:
                model.ub[j] = 0
            continue
        blockers = []
        for child, amount in sorted(components.items()):
            key = (child, amount, k)
            if key not in shortages:
                if child in data['raw']:
                    inventory = meta['raw_stocks'][child, k]
                    step = 1.0 if k == 0 else raw_step
                else:
                    inventory = meta['v']['I', child, k]
                    step = 1.0
                # Do not silently weaken the rule for a numerically unresolved lattice.
                if step / 2 <= 1e-5 or amount - step / 2 == amount:
                    raise ValueError('Expected raw-stock precision is too fine for certified immediate starts')
                cutoff = amount - step / 2
                upper = float(model.ub[inventory])
                binary = model.var(('material_short', child, amount, k), 1, integer=True)
                big_m = max(0.0, upper - cutoff)
                model.rows.append({inventory: 1, binary: big_m})
                model.lo.append(-float('inf'))
                model.hi.append(upper if big_m else cutoff)
                model.labels.append('immediate_start_material_shortage')
                shortages[key] = binary
            blockers.append(shortages[key])
        for j in waiting_vars:
            model.rows.append({j: 1, **{b: -float(model.ub[j]) for b in blockers}})
            model.lo.append(-float('inf'))
            model.hi.append(0)
            model.labels.append('immediate_start_no_idle')
    meta['production_start_rule'] = RULE
    return model, meta


def validate_plan(model, meta, values, data):
    """Independent semantic check; a small big-M violation must not become idle work."""
    if meta.get('production_start_rule') != RULE:
        raise ValueError('Missing immediate-start model identity')
    waits = Counter()
    for (kind, product, k, age), j in meta['av'].items():
        if kind == 'u':
            waits[product, k] += values[j]
    for (product, k), quantity in waits.items():
        if quantity < 0.5:
            continue
        components = requirements(data, product)
        stocks = {
            child: values[meta['raw_stocks'][child, k] if child in data['raw'] else meta['v']['I', child, k]]
            for child in components
        }
        if all(stocks[child] >= amount - 1e-7 for child, amount in components.items()):
            raise ValueError(f'{RULE}: feasible materials but planned waiting product={product}, k={k}')
    return dict(production_start_rule=RULE, no_avoidable_waiting=True)
